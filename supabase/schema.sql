-- ---------- PERFILES ----------
create table public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  nombre     text,
  apellido   text,
  alias      text,
  pais       text,
  provincia  text,
  localidad  text,
  role       text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now(),
  constraint alias_formato check (alias is null or alias ~ '^[A-Za-z0-9._-]{3,20}$')
);
create unique index profiles_alias_unico on public.profiles (lower(alias));
alter table public.profiles enable row level security;

-- ¿La persona que hace la consulta es administradora?
create or replace function public.is_admin() returns boolean
language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

create policy "perfil: ver el propio o admin" on public.profiles
  for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "perfil: editar el propio" on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Nadie puede cambiarse el rol desde la app: solo se permiten estas columnas
revoke update on public.profiles from anon, authenticated;
grant update (nombre, apellido, alias, pais, provincia, localidad) on public.profiles to authenticated;

-- Al registrarse, crea el perfil con los datos enviados en la metadata del alta
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nombre, apellido, alias, pais, provincia, localidad)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nombre',   new.raw_user_meta_data->>'given_name'),
    coalesce(new.raw_user_meta_data->>'apellido', new.raw_user_meta_data->>'family_name'),
    nullif(new.raw_user_meta_data->>'alias', ''),
    new.raw_user_meta_data->>'pais',
    new.raw_user_meta_data->>'provincia',
    new.raw_user_meta_data->>'localidad'
  );
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ¿Está libre este alias? (la app lo consulta antes de registrar)
create or replace function public.alias_available(a text) returns boolean
language sql security definer stable set search_path = public as $$
  select not exists (select 1 from public.profiles where lower(alias) = lower(a) and id is distinct from auth.uid());
$$;
grant execute on function public.alias_available(text) to anon, authenticated;

-- ---------- LIBROS (catálogo compartido) ----------
create table public.books (
  id         bigint generated by default as identity primary key,
  title      text not null,
  author     text not null,
  pages      int,
  genre      text,
  isbn       text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.books enable row level security;
create policy "libros: lectura pública" on public.books
  for select to anon, authenticated using (true);
create policy "libros: carga por usuarios" on public.books
  for insert to authenticated with check (created_by = auth.uid());
create policy "libros: edita admin" on public.books
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

