-- ---------- LECTURAS (la biblioteca de cada persona) ----------
create table public.reading_entries (
  id          bigint generated by default as identity primary key,
  user_id     uuid   not null references public.profiles(id) on delete cascade,
  book_id     bigint not null references public.books(id)    on delete cascade,
  status      text   not null default 'Quiero leer' check (status in ('Quiero leer','Leyendo','Leído')),
  formats     text[] not null default '{"Físico"}',
  finished_on date,
  rating      smallint check (rating between 1 and 5),
  updated_at  timestamptz not null default now(),
  unique (user_id, book_id)
);
alter table public.reading_entries enable row level security;
create policy "lecturas: solo la persona dueña" on public.reading_entries
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ---------- RESEÑAS (con moderación) ----------
create table public.reviews (
  id            bigint generated by default as identity primary key,
  user_id       uuid   not null references public.profiles(id) on delete cascade,
  book_id       bigint not null references public.books(id)    on delete cascade,
  body          text   not null check (length(trim(body)) > 0 and length(body) <= 2000),
  rating        smallint check (rating between 1 and 5),
  status        text   not null default 'pending' check (status in ('pending','approved','rejected')),
  reject_reason text,
  moderated_by  uuid references auth.users(id),
  moderated_at  timestamptz,
  created_at    timestamptz not null default now(),
  unique (user_id, book_id)
);
alter table public.reviews enable row level security;
-- Cada persona ve y maneja solo sus reseñas. Las aprobadas de otras personas se leen con book_reviews().
create policy "reseñas: ver las propias"  on public.reviews for select to authenticated using (user_id = auth.uid());
create policy "reseñas: crear las propias" on public.reviews for insert to authenticated with check (user_id = auth.uid());
create policy "reseñas: editar las propias" on public.reviews for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "reseñas: borrar las propias" on public.reviews for delete to authenticated using (user_id = auth.uid());

-- Regla de moderación: una reseña nueva o con el texto cambiado siempre queda "pending".
-- Quien no es admin no puede aprobarse a sí mismo.
create or replace function public.reviews_guard() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.status := 'pending'; new.reject_reason := null; new.moderated_by := null; new.moderated_at := null;
    return new;
  end if;
  if public.is_admin() then return new; end if;
  if new.body is distinct from old.body then
    new.status := 'pending'; new.reject_reason := null; new.moderated_by := null; new.moderated_at := null;
  else
    new.status := old.status; new.reject_reason := old.reject_reason;
    new.moderated_by := old.moderated_by; new.moderated_at := old.moderated_at;
  end if;
  return new;
end $$;
create trigger reviews_guard_trg before insert or update on public.reviews
  for each row execute function public.reviews_guard();

-- ---------- FUNCIONES QUE USA LA APP ----------
-- Libros con su calificación promedio
create or replace function public.books_with_stats()
returns table (id bigint, title text, author text, pages int, genre text, isbn text, avg_rating numeric, n_ratings bigint)
language sql security definer stable set search_path = public as $$
  select b.id, b.title, b.author, b.pages, b.genre, b.isbn, round(avg(e.rating)::numeric, 1), count(e.rating)
  from public.books b left join public.reading_entries e on e.book_id = b.id and e.rating is not null
  group by b.id order by b.id;
$$;
grant execute on function public.books_with_stats() to anon, authenticated;

-- Reseñas aprobadas de un libro (+ las propias, en cualquier estado), con el alias de quien las escribió
create or replace function public.book_reviews(p_book bigint)
returns table (id bigint, alias text, rating smallint, body text, status text, reject_reason text, mine boolean)
language sql security definer stable set search_path = public as $$
  select r.id, p.alias, r.rating, r.body, r.status,
         case when r.user_id = auth.uid() then r.reject_reason end,
         (r.user_id = auth.uid())
  from public.reviews r join public.profiles p on p.id = r.user_id
  where r.book_id = p_book and (r.status = 'approved' or r.user_id = auth.uid())
  order by r.created_at desc;
$$;
grant execute on function public.book_reviews(bigint) to anon, authenticated;

-- Solo admin: reseñas pendientes
create or replace function public.pending_reviews()
returns table (id bigint, book_id bigint, title text, alias text, rating smallint, body text)
language sql security definer stable set search_path = public as $$
  select r.id, r.book_id, b.title, p.alias, r.rating, r.body
  from public.reviews r
  join public.books b on b.id = r.book_id
  join public.profiles p on p.id = r.user_id
  where public.is_admin() and r.status = 'pending'
  order by r.created_at;
$$;

-- Solo admin: aprobar o rechazar
create or replace function public.moderate_review(p_id bigint, p_ok boolean, p_reason text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  update public.reviews
     set status = case when p_ok then 'approved' else 'rejected' end,
         reject_reason = case when p_ok then null else p_reason end,
         moderated_by = auth.uid(), moderated_at = now()
   where id = p_id;
end $$;

revoke execute on function public.pending_reviews()                      from public, anon;
revoke execute on function public.moderate_review(bigint, boolean, text) from public, anon;
grant  execute on function public.pending_reviews()                      to authenticated;
grant  execute on function public.moderate_review(bigint, boolean, text) to authenticated;

